/// `msg.streamBegin`. The server's `BeginStreamRequest`: where the reply goes, the idempotency
/// key of the message it will become, and what to draw while it runs.
///
/// **Address it like `msg.send`**: [conversationId], else [receiverId], else [groupId] — the first
/// one set wins, and none is `1001`. The audience is fixed here, at begin: whoever is a participant
/// now receives every frame, however long the stream runs.
///
/// **Options are checked at begin, not at complete.** A client may not set
/// [ImPushConfig.title] / [ImPushConfig.body] (`1103`), nor stream an unstored media message
/// (`persistent: false` or `onlineOnly` with an image / voice / video / file) while the app
/// moderates content (`1103`). [options] travels nested, where the server's binder matches member
/// names case-sensitively — which is why it is an [ImMessageOptions] and not a map.
///
/// The begin-time refusals are `msg.send`'s: `1104` banned, `1408` muted, `1303` blocked, `1302` not
/// a friend where the app requires it, `1500` / `1501` / `1503` / `1506` / `1505` for the group.
/// `1003` past 60 begins a minute per user.
///
/// 寻址方式与 msg.send 相同（conversationId → receiverId → groupId，都没有是 1001），受众在开流时定死。
/// options 在开流时校验：客户端不能设推送标题/正文，审核开启时不能流式发送不落库的媒体（都是 1103）。
class ImBeginStreamRequest implements ImRequestBody {
  ImBeginStreamRequest({
    this.conversationId,
    this.receiverId,
    this.groupId,
    String? clientMsgId,
    this.contentType = ImMessageContentType.text,
    this.placeholder,
    this.options,
    this.extensions,
  }) : clientMsgId = clientMsgId ?? imNewClientMsgId();

  final String? conversationId;

  /// The other end of a single chat. Yourself is allowed: a self-chat streams to your own devices.
  final String? receiverId;

  final String? groupId;

  /// Idempotency key of the **message** this stream becomes, **required by the server** (`1001`
  /// without one) and generated when you do not supply one. It is not regenerated by the server:
  /// the finished message carries exactly this value, so keep it — re-sending the text later as an
  /// ordinary `msg.send` with the same key, after a rejected complete, produces the one message
  /// rather than a duplicate.
  final String clientMsgId;

  /// The content type of the finished message. Text unless you say otherwise; the server does not
  /// use [ImMessageContentType.stream] for anything.
  final ImMessageContentType contentType;

  /// Whatever the receivers should draw before the first fragment — an assistant's name, an avatar.
  /// Free-form, echoed once in the opening `evt.stream` frame ([ImStreamEvent.placeholder]) and
  /// nowhere else: it is not part of the finished message.
  final Map<String, dynamic>? placeholder;

  /// The finished message's options, exactly as for `msg.send`.
  final ImMessageOptions? options;

  /// Merged into the finished message's extensions; on a key both name, complete's value wins.
  final Map<String, dynamic>? extensions;

  @override
  Map<String, Object?> toJson() => imBody(<String, Object?>{
        'conversationId': conversationId,
        'receiverId': receiverId,
        'groupId': groupId,
        'clientMsgId': clientMsgId,
        'contentType': contentType.wireValue,
        'placeholder': placeholder,
        'options': options?.toJson(),
        'extensions': extensions,
      });
}

/// `msg.streamAppend`. The server's `StreamAppendRequest`: the next fragment of an open stream.
///
/// The server numbers fragments itself, in the order it receives them — 1, 2, 3… — so appends from
/// one producer must not overlap: await each before sending the next. An empty [delta] is accepted
/// and dropped (no frame, no index, no rate token). `1401` past 4096 characters, or once the
/// accumulated text would exceed the limit (16384 characters, less on an app with a small message
/// size) — **the stream stays open after a `1401`**, so abort or complete it. `1003` past 100
/// appends a second; `1002` once the stream has been completed, aborted or reaped; `1103` when the
/// stream is someone else's.
///
/// 分片序号由服务端按收到的顺序编：同一个生产者的追加要一条一条 await，不能并发。
/// 空 delta 被接受并丢弃；1401 之后流仍然开着，要自己 abort 或 complete。
class ImStreamAppendRequest implements ImRequestBody {
  const ImStreamAppendRequest({required this.streamId, required this.delta});

  /// [ImStreamHandle.streamId].
  final String streamId;

  final String delta;

  @override
  Map<String, Object?> toJson() => <String, Object?>{'streamId': streamId, 'delta': delta};
}

/// `msg.streamComplete`. The server's `CompleteStreamRequest`: finish the stream into one ordinary
/// message.
///
/// With [content] null (or empty) the message's content is `{"text": <every fragment, joined>}`;
/// a [content] **replaces** the fragments — a producer may send a cleaned-up version of what it
/// streamed. [extensions] are merged over the begin call's.
///
/// The result is `msg.send`'s, and so are its refusals: moderation, a tenant webhook, a store that
/// is down. **Either way the stream is over**: on a rejection the receivers get a terminal frame
/// with an [ImStreamEvent.abortReason] and no message exists — re-send the text as an ordinary
/// `msg.send` with the begin call's `clientMsgId` if you still want it delivered. A second complete
/// (or an abort after one) is `1002`.
///
/// content 为空时最终消息是 `{"text": 全部分片拼接}`，给了就整体替换。被发送管线拒绝时流同样结束，
/// 接收方收到带 abortReason 的终帧、不产生消息。第二次 complete 是 1002。
class ImCompleteStreamRequest implements ImRequestBody {
  const ImCompleteStreamRequest({required this.streamId, this.content, this.extensions});

  final String streamId;

  /// Replaces the accumulated fragments when set; shaped by the begin call's content type.
  final Map<String, dynamic>? content;

  final Map<String, dynamic>? extensions;

  @override
  Map<String, Object?> toJson() => imBody(<String, Object?>{
        'streamId': streamId,
        'content': content,
        'extensions': extensions,
      });
}

/// `msg.streamAbort`. The server's `StreamAbortRequest`: end the stream without producing a
/// message — the generator failed, the user pressed stop.
///
/// Worth calling rather than going quiet: the receivers' placeholder clears now instead of after
/// the idle sweep (30 to 60 seconds after the last append). [reason] is shown to them as
/// [ImStreamEvent.abortReason]; blank becomes "aborted by the producer", and it is cut to 256
/// characters. `1002` when the stream is already over.
class ImStreamAbortRequest implements ImRequestBody {
  const ImStreamAbortRequest({required this.streamId, this.reason});

  final String streamId;

  final String? reason;

  @override
  Map<String, Object?> toJson() => imBody(<String, Object?>{
        'streamId': streamId,
        'reason': reason,
      });
}

