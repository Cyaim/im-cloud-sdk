/// What `msg.streamBegin` answers. The server's `StreamHandle`.
class ImStreamHandle {
  const ImStreamHandle({
    required this.streamId,
    required this.conversationId,
    this.startedAt = 0,
    this.idleTimeoutSeconds = 0,
  });

  factory ImStreamHandle.fromJson(Map<String, dynamic> json) => ImStreamHandle(
        streamId: imStringOr(json['streamId']),
        conversationId: imStringOr(json['conversationId']),
        startedAt: imIntOr(json['startedAt']),
        idleTimeoutSeconds: imIntOr(json['idleTimeoutSeconds']),
      );

  /// `st_…`; what the other three calls take.
  final String streamId;

  /// The conversation the address resolved to.
  final String conversationId;

  /// Unix ms. The finished message's `sendTime`.
  final int startedAt;

  /// Seconds of silence after which the server abandons the stream (30 today): append, or abort,
  /// before then. There is no limit on the stream's total length, only on its pauses.
  final int idleTimeoutSeconds;
}

// ---------------------------------------------------------------------------- the producer's handle

/// One open stream, for a producer that would rather not carry the stream id around:
/// `begin` → `append`* → `complete` | `abort`, each one the raw call on [ImMsgApi] underneath.
///
/// Holds no state beyond the [handle] and adds no rule of its own — a second [complete] is the
/// server's `1002`, exactly as through [ImMsgApi.streamComplete].
///
/// 生产者用的小句柄：底下就是 ImMsgApi 的四个原始调用，自身不加任何规则。
final class ImStreamWriter {
  ImStreamWriter(this._msg, this.handle);

  /// Opens a stream through [msg] and returns its writer.
  static Future<ImStreamWriter> begin(
    ImMsgApi msg,
    ImBeginStreamRequest request, [
    ImCancelToken? cancel,
  ]) async =>
      ImStreamWriter(msg, await msg.streamBegin(request, cancel));

  final ImMsgApi _msg;

  /// What `msg.streamBegin` answered.
  final ImStreamHandle handle;

  String get streamId => handle.streamId;

  /// `msg.streamAppend`. Await it before the next one: the server numbers fragments by arrival.
  Future<void> append(String delta, [ImCancelToken? cancel]) =>
      _msg.streamAppend(ImStreamAppendRequest(streamId: streamId, delta: delta), cancel);

  /// `msg.streamComplete`. [content] null sends the fragments, joined, as `{"text": …}`.
  Future<ImSendResult> complete({
    Map<String, dynamic>? content,
    Map<String, dynamic>? extensions,
    ImCancelToken? cancel,
  }) =>
      _msg.streamComplete(
        ImCompleteStreamRequest(streamId: streamId, content: content, extensions: extensions),
        cancel,
      );

  /// `msg.streamAbort`.
  Future<void> abort([String? reason, ImCancelToken? cancel]) =>
      _msg.streamAbort(ImStreamAbortRequest(streamId: streamId, reason: reason), cancel);
}

// ---------------------------------------------------------------------------- evt.stream

/// Which of the four frames an [ImStreamEvent] is. Derived from `index` / `done` / `messageId` —
/// the server sends no phase field — so a closed set is right here.
enum ImStreamPhase {
  /// `index` 0, not done: a stream is starting; draw the placeholder. Carries no delta.
  begin,

  /// `index` ≥ 1, not done: the next fragment. Sent at low priority, so under backpressure the
  /// server drops it rather than a message — and a queued fragment can arrive **after** the
  /// terminal frame and the finished message, which jump ahead of it.
  delta,

  /// Done, with a `messageId`: the stream became that message, which arrives (or arrived) on
  /// `ImClient.messages`.
  completed,

  /// Done, without a `messageId`: the producer aborted, went quiet past the idle limit, or its
  /// complete was rejected by the send pipeline. No message exists.
  aborted,
}

/// One `evt.stream` frame, as `ImClient.streamEvents` delivers it. The server's `StreamDelta`
/// (and `StreamBeginFrame`, which is the same shape plus [placeholder]).
///
/// **Indices run 0, 1, 2… and the terminal frame is one past the last fragment**, so a hole is a
/// fragment this connection missed. There is no resend and no catch-up: on a hole, on joining a
/// stream midway (a first frame with an index above 0) or after being offline, do not try to
/// repair — wait for the finished message on `ImClient.messages`. [ImStreamAssembler] does that
/// bookkeeping.
///
/// **None of this is a message.** A frame has no conversation seq ([seq] on the terminal frame is
/// the finished message's, for matching only), moves no cursor and is never fetched again.
///
/// 序号 0、1、2……，终帧是最后一片加一，中间的洞就是这条连接漏掉的分片。没有重发、没有补齐：
/// 遇到洞、中途加入或离线过，都不要修，等 messages 里的最终消息。这些帧都不是消息，不动游标。
class ImStreamEvent {
  const ImStreamEvent({
    required this.streamId,
    required this.conversationId,
    required this.senderId,
    required this.index,
    this.delta,
    this.done = false,
    this.messageId,
    this.seq,
    this.abortReason,
    this.placeholder,
    this.data = const <String, dynamic>{},
  });

  /// Decodes an `evt.stream` payload, or returns null for anything without a stream id.
  static ImStreamEvent? tryParse(Object? data) {
    final Map<String, dynamic>? json = imMapOrNull(data);
    if (json == null) return null;

    final String? streamId = imString(json['streamId']);
    if (streamId == null || streamId.isEmpty) return null;

    // A message id travels quoted (WriteAsString); a bare number is read too rather than dropped.
    // 消息 id 按字符串传；遇到裸数字也照读，不丢帧。
    final Object? messageId = json['messageId'];
    final String? id = messageId == null ? null : imId(messageId);

    return ImStreamEvent(
      streamId: streamId,
      conversationId: imStringOr(json['conversationId']),
      senderId: imStringOr(json['senderId']),
      index: imIntOr(json['index']),
      delta: imString(json['delta']),
      done: imBool(json['done']),
      messageId: id == null || id.isEmpty ? null : id,
      seq: imInt(json['seq']),
      abortReason: imString(json['abortReason']),
      placeholder: imMapOrNull(json['placeholder']),
      data: json,
    );
  }

  /// `st_…`, the same id the producer got from `msg.streamBegin`.
  final String streamId;

  final String conversationId;

  /// The producer.
  final String senderId;

  /// 0 for the opening frame, 1… for fragments, one past the last fragment for the terminal frame.
  final int index;

  /// The fragment's text, on a [ImStreamPhase.delta] frame only.
  final String? delta;

  /// True on the terminal frame only.
  final bool done;

  /// The finished message's id, on a [ImStreamPhase.completed] frame only — match it against
  /// [ImMessage.messageId] to swap the placeholder for the stored message.
  final String? messageId;

  /// The finished message's conversation seq, on a [ImStreamPhase.completed] frame only. For
  /// matching: the message itself moves the cursor when it arrives on `ImClient.messages`.
  final int? seq;

  /// Why no message exists, on a [ImStreamPhase.aborted] frame only: the producer's reason, "the
  /// producer stopped sending for 30s", or the send pipeline's refusal.
  final String? abortReason;

  /// The producer's [ImBeginStreamRequest.placeholder], on the opening frame only.
  final Map<String, dynamic>? placeholder;

  /// The whole payload as the server sent it, for a field this build does not type.
  final Map<String, dynamic> data;

  ImStreamPhase get phase => done
      ? (messageId != null ? ImStreamPhase.completed : ImStreamPhase.aborted)
      : (index == 0 ? ImStreamPhase.begin : ImStreamPhase.delta);
}

// ---------------------------------------------------------------------------- assembling

/// Where an assembled stream stands.
enum ImStreamStatus {
  /// No terminal frame yet.
  streaming,

  /// The stream became a message: [ImStreamState.messageId].
  completed,

  /// The stream ended without a message: [ImStreamState.abortReason].
  aborted,
}

/// One stream as [ImStreamAssembler] has put it together so far. A snapshot: a later frame
/// produces a new one.
class ImStreamState {
  const ImStreamState({
    required this.streamId,
    required this.conversationId,
    required this.senderId,
    required this.text,
    required this.status,
    required this.sawBegin,
    required this.fragments,
    required this.missingFragments,
    this.placeholder,
    this.messageId,
    this.seq,
    this.abortReason,
  });

  final String streamId;
  final String conversationId;
  final String senderId;

  /// Every fragment received, joined in index order — holes skipped. With no hole and status
  /// [ImStreamStatus.completed] this is the text the server stored, **unless the producer completed
  /// with explicit content**, which replaces it; so once the finished message is in hand, render
  /// that, not this.
  final String text;

  final ImStreamStatus status;

  /// Whether the opening frame arrived. False after joining midway: no [placeholder] to draw.
  final bool sawBegin;

  final Map<String, dynamic>? placeholder;

  /// How many fragments were received.
  final int fragments;

  /// Fragments known to be missing: below the highest index seen or, once finished, below the
  /// terminal frame's. Can fall back to 0 after the terminal frame, when a queued fragment it
  /// overtook arrives.
  final int missingFragments;

  /// On [ImStreamStatus.completed]: the stored message's id.
  final String? messageId;

  /// On [ImStreamStatus.completed]: the stored message's conversation seq.
  final int? seq;

  /// On [ImStreamStatus.aborted]: why.
  final String? abortReason;

  bool get isFinished => status != ImStreamStatus.streaming;

  /// [text] is short of what the producer sent. Do not repair it: wait for (or keep) the finished
  /// message, which carries the whole text.
  bool get hasGap => missingFragments > 0;
}

/// Puts `evt.stream` frames back together, one [ImStreamState] per stream, by the server's rules:
/// fragments ordered by index, duplicates ignored, a hole counted rather than repaired, the
/// terminal frame deciding completed or aborted.
///
/// ```dart
/// im.streamEvents.transform(ImStreamAssembler()).listen((ImStreamState s) { … });
/// ```
///
/// **The frames are not guaranteed to arrive in the order they were sent.** Fragments are low
/// priority and the opening frame, the terminal frame and the finished message are not, so a queued
/// fragment can arrive after the terminal frame — and after the message itself. A finished stream is
/// therefore remembered (the last [rememberFinished] of them) and a late fragment updates it, where
/// it would otherwise open a stream that never ends; a late opening or terminal frame is ignored.
/// The finished message on `ImClient.messages` may also come before or after the terminal frame:
/// match it on [ImStreamState.messageId] either way.
///
/// **A stream whose terminal frame never arrives** — the connection dropped while it ran — stays
/// [ImStreamStatus.streaming] here forever: the server does not replay frames. Its message, if it
/// was completed, still reaches you through the normal resume. Call [forget] (or [clear]) when you
/// stop drawing it; frames for a forgotten stream are ignored from then on.
///
/// 分片是低优先级，开流帧、终帧和最终消息不是，所以排队中的分片可能晚于终帧乃至最终消息到达：
/// 已结束的流会被记住，迟到的分片补进它，而不是新开一条永不结束的流。终帧没到（连接断了）的流
/// 在这里一直是 streaming——服务端不重放；不再画它时调用 forget / clear。
final class ImStreamAssembler extends StreamTransformerBase<ImStreamEvent, ImStreamState> {
  ImStreamAssembler({this.rememberFinished = 256});

  /// How many finished streams are kept for late fragments.
  final int rememberFinished;

  final Map<String, _Assembly> _active = <String, _Assembly>{};

  // Insertion-ordered: the oldest finished stream is evicted first.
  final LinkedHashMap<String, _Assembly> _finished = LinkedHashMap<String, _Assembly>();

  /// The streams without a terminal frame yet.
  List<ImStreamState> get active =>
      <ImStreamState>[for (final _Assembly assembly in _active.values) assembly.snapshot()];

  /// The stream's current state, active or remembered.
  ImStreamState? stateOf(String streamId) => (_active[streamId] ?? _finished[streamId])?.snapshot();

  /// Folds one frame in. Returns the stream's new state, or null when the frame changed nothing — a
  /// duplicate, a late opening or terminal frame, or a frame for a forgotten stream.
  ImStreamState? add(ImStreamEvent event) {
    final _Assembly? finished = _finished[event.streamId];
    if (finished != null) {
      if (event.phase != ImStreamPhase.delta || finished.forgotten) return null;
      return finished.addFragment(event.index, event.delta ?? '') ? finished.snapshot() : null;
    }

    final _Assembly assembly = _active.putIfAbsent(
      event.streamId,
      () => _Assembly(event.streamId, event.conversationId, event.senderId),
    );

    switch (event.phase) {
      case ImStreamPhase.begin:
        if (assembly.sawBegin) return null;
        assembly
          ..sawBegin = true
          ..placeholder = event.placeholder;
      case ImStreamPhase.delta:
        if (!assembly.addFragment(event.index, event.delta ?? '')) return null;
      case ImStreamPhase.completed:
      case ImStreamPhase.aborted:
        assembly
          ..status = event.phase == ImStreamPhase.completed
              ? ImStreamStatus.completed
              : ImStreamStatus.aborted
          ..messageId = event.messageId
          ..seq = event.seq
          ..abortReason = event.abortReason
          ..fragmentCount = event.index > 0 ? event.index - 1 : 0;
        _active.remove(event.streamId);
        _remember(assembly);
    }

    return assembly.snapshot();
  }

  /// Stops tracking [streamId]: returns its last state, and ignores its frames from now on.
  ImStreamState? forget(String streamId) {
    final _Assembly? assembly = _active.remove(streamId) ?? _finished[streamId];
    if (assembly == null) return null;
    assembly.forgotten = true;
    _remember(assembly);
    return assembly.snapshot();
  }

  /// Forgets every active stream and returns their last states — for a screen that is going away,
  /// or a connection that dropped while streams were open.
  List<ImStreamState> clear() => <ImStreamState>[
        for (final String streamId in _active.keys.toList(growable: false)) forget(streamId)!,
      ];

  void _remember(_Assembly assembly) {
    _finished
      ..remove(assembly.streamId)
      ..[assembly.streamId] = assembly;
    while (_finished.length > rememberFinished) {
      _finished.remove(_finished.keys.first);
    }
  }

  @override
  Stream<ImStreamState> bind(Stream<ImStreamEvent> stream) =>
      stream.map(add).where((ImStreamState? state) => state != null).cast<ImStreamState>();
}

/// The mutable half of one stream. Fragments that continue the text are appended to [_text];
/// ones that arrive past a hole wait in [_pending] until the hole fills (it may never).
class _Assembly {
  _Assembly(this.streamId, this.conversationId, this.senderId);

  final String streamId;
  final String conversationId;
  final String senderId;

  bool sawBegin = false;
  bool forgotten = false;
  Map<String, dynamic>? placeholder;
  ImStreamStatus status = ImStreamStatus.streaming;
  String? messageId;
  int? seq;
  String? abortReason;

  /// Known from the terminal frame: one less than its index.
  int? fragmentCount;

  final StringBuffer _text = StringBuffer();
  int _contiguous = 0; // fragments 1…_contiguous are in _text
  final SplayTreeMap<int, String> _pending = SplayTreeMap<int, String>();

  /// False for a duplicate (or an index below 1, which no fragment has).
  bool addFragment(int index, String delta) {
    if (index <= _contiguous || _pending.containsKey(index)) return false;

    if (index != _contiguous + 1) {
      _pending[index] = delta;
      return true;
    }

    _text.write(delta);
    _contiguous = index;
    while (_pending.isNotEmpty && _pending.firstKey() == _contiguous + 1) {
      _contiguous++;
      _text.write(_pending.remove(_contiguous));
    }
    return true;
  }

  ImStreamState snapshot() {
    final int received = _contiguous + _pending.length;
    final int highest = _pending.isEmpty ? _contiguous : _pending.lastKey()!;
    final int expected =
        fragmentCount != null && fragmentCount! > highest ? fragmentCount! : highest;

    return ImStreamState(
      streamId: streamId,
      conversationId: conversationId,
      senderId: senderId,
      text: _pending.isEmpty ? _text.toString() : '$_text${_pending.values.join()}',
      status: status,
      sawBegin: sawBegin,
      placeholder: placeholder,
      fragments: received,
      missingFragments: expected - received,
      messageId: messageId,
      seq: seq,
      abortReason: abortReason,
    );
  }
}
