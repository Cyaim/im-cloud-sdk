/// `msg.streamBegin` / `msg.streamAppend` / `msg.streamComplete` / `msg.streamAbort` — a reply
/// typed out while it is being generated (T4) — and the `evt.stream` frames the other end sees.
/// [ImMsgApi] sends the four calls; `ImClient.streamEvents` decodes the frames.
///
/// In a file of its own because the family is typed whole or not at all (`sdk/CONTRACT.md` §3), and
/// a reader asking "how does a streamed reply reach the screen" should find one place.
///
/// **The platform calls no model.** The producer — a tenant's bot, an AI desk agent, any client —
/// opens a stream, appends fragments as its own generator yields them, and completes it. Who may
/// stream is whoever may `msg.send` there, as themselves only: single chats (self-chat included)
/// and groups of up to 200 members; a chat room, system or assistant conversation is `1008`.
///
/// **Fragments are ephemeral; the finished stream is an ordinary message.** Every `evt.stream`
/// frame goes to the participants online at that moment — the producer's own connections included
/// — and is never stored, never carries a conversation seq, and is never repaired or synced:
/// it does not touch a cursor and nothing in this package asks for it again. `msg.streamComplete`
/// sends the assembled text through the normal send path, so the result arrives on
/// `ImClient.messages` as an ordinary [ImMessage] with a real seq, the begin call's `clientMsgId`
/// and `sendTime` = when the stream started — and goes through the normal cursor and gap-repair
/// path like any other message. A client that was offline for the whole generation gets that one
/// message and nothing else.
///
/// 平台不调用任何模型：生产者自己开流、追加分片、收流，权限与 msg.send 相同，且只能以自己的身份。
/// 分片只投在线设备（含生产者自己的连接），不落库、没有会话 seq、不补洞、不同步、不动游标；
/// 收流之后组装成一条普通消息，带真实 seq 经 messages 到达，并照常走游标与补洞路径。
library;

