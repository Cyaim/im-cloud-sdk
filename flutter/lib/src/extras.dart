// ---------------------------------------------------------------------------- scheduled messages

/// `msg.schedule`. The server's `ScheduleRequest`: a message to send at [sendAt], **flat** — the
/// message's own members sit beside [sendAt], not nested under a `message` key.
///
/// It carries the members of `msg.send` the scheduler stores and replays, and deliberately not
/// `options` or `sendTime`: the server's type has neither, so a scheduled message goes out with the
/// default options. That is why this is its own type and not an [ImSendMessageRequest].
///
/// **Address it like `msg.send`**: [conversationId], else [groupId], else [receiverId] — the first
/// one set wins, and none is `1001`. Access is checked now, as for `msg.send` (not a member, blocked,
/// muted…), and again when it fires.
///
/// **Rules** (the deployment's `IM:Extras`, defaults shown): [sendAt] at least 10 seconds ahead and at
/// most 90 days ahead (`1001` either way); an empty [content] is `1001`; `1003` past 120 schedules
/// created per user per hour; `1006` while the caller already has 100 pending. No add-on or app
/// setting gates it.
///
/// **Not idempotent.** Repeating a `msg.schedule` whose reply was lost creates a second schedule;
/// [clientMsgId] only de-duplicates the eventual send. After a timeout, list with `msg.scheduled`
/// before scheduling again.
///
/// 扁平结构：消息的成员与 sendAt 并列，不嵌在 message 下；服务端类型没有 options 与 sendTime，所以这里也没有。
/// sendAt 至少提前 10 秒、至多 90 天；每人每小时最多建 120 条（1003），同时待发最多 100 条（1006）。
/// msg.schedule 本身不幂等：丢了答复再发一次会建出第二条，clientMsgId 只对最终那次发送去重。
class ImScheduleRequest implements ImRequestBody {
  const ImScheduleRequest({
    required this.sendAt,
    this.conversationId,
    this.receiverId,
    this.groupId,
    this.conversationType,
    this.clientMsgId,
    this.contentType = ImMessageContentType.text,
    required this.content,
    this.mentionAll = false,
    this.mentionedUserIds,
    this.quoteMessageId,
    this.threadRootId,
    this.extensions,
  });

  /// Plain text at [sendAt], the common case.
  factory ImScheduleRequest.text(
    String text, {
    required int sendAt,
    String? conversationId,
    String? receiverId,
    String? groupId,
    String? clientMsgId,
    List<String>? mentionedUserIds,
    bool mentionAll = false,
    String? quoteMessageId,
  }) =>
      ImScheduleRequest(
        sendAt: sendAt,
        conversationId: conversationId,
        receiverId: receiverId,
        groupId: groupId,
        clientMsgId: clientMsgId,
        content: <String, dynamic>{'text': text},
        mentionedUserIds: mentionedUserIds,
        mentionAll: mentionAll,
        quoteMessageId: quoteMessageId,
      );

  /// When to send, unix ms, by the server's clock. The message goes out on the scheduler's first
  /// sweep at or after this moment — the sweep runs every 15 seconds by default — so expect it up
  /// to that much late, never early.
  /// 按服务端时钟；调度器默认每 15 秒扫一次，所以会在 sendAt 之后的第一次扫描发出——可能晚到这么多，不会早。
  final int sendAt;

  final String? conversationId;

  /// The other end of a single chat.
  final String? receiverId;

  final String? groupId;

  /// Bound by the server but not used to address the message; the address members decide.
  final ImConversationType? conversationType;

  /// Idempotency key of the **eventual send**. Optional here, unlike `msg.send`, and not generated by
  /// this package: when it is left out the server uses `sch-<scheduleId>`, which already makes a
  /// re-dispatch after a server crash collapse into the one message.
  /// 可选，本包不自动生成：缺省时服务端用 `sch-<scheduleId>`，已足以让崩溃后的重新派发收敛成一条消息。
  final String? clientMsgId;

  final ImMessageContentType contentType;

  /// Shaped by [contentType]; must not be empty (`1001`).
  final Map<String, dynamic> content;

  final bool mentionAll;
  final List<String>? mentionedUserIds;

  /// Digits, as [ImMessage.messageId] holds it.
  final String? quoteMessageId;

  final String? threadRootId;
  final Map<String, dynamic>? extensions;

  @override
  Map<String, Object?> toJson() => imBody(<String, Object?>{
        'sendAt': sendAt,
        'conversationId': conversationId,
        'receiverId': receiverId,
        'groupId': groupId,
        'conversationType': conversationType?.wireValue,
        'clientMsgId': clientMsgId,
        'contentType': contentType.wireValue,
        'content': content,
        'mentionAll': mentionAll,
        'mentionedUserIds': mentionedUserIds,
        'quoteMessageId': quoteMessageId,
        'threadRootId': threadRootId,
        'extensions': extensions,
      });
}

