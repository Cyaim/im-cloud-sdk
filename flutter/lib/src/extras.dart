  final String folderId;

  @override
  Map<String, Object?> toJson() => <String, Object?>{'folderId': folderId};
}

/// One folder, as `conv.folders` lists and `conv.upsertFolder` answers. The server's
/// `ConversationFolder`.
class ImConversationFolder {
  const ImConversationFolder({
    required this.folderId,
    required this.name,
    this.order = 0,
    this.tags = const <String>[],
    this.unreadOnly = false,
    this.types,
  });

  factory ImConversationFolder.fromJson(Map<String, dynamic> json) => ImConversationFolder(
        folderId: imStringOr(json['folderId']),
        name: imStringOr(json['name']),
        order: imIntOr(json['order']),
        tags: imStringList(json['tags']),
        unreadOnly: imBool(json['unreadOnly']),
        types: json['types'] is List
            ? <ImConversationType>[
                for (final int value in imIntList(json['types'])) ImConversationType(value),
              ]
            : null,
      );

  final String folderId;

  /// Trimmed and cut to 64 characters by the server.
  final String name;

  final int order;

  /// As saved: trimmed, de-duplicated.
  final List<String> tags;

  final bool unreadOnly;

  /// Null means every conversation type — the server stores an empty list as null, and omits it.
  final List<ImConversationType>? types;
}

