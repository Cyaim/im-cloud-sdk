/// Where a schedule stands, derived from [ImScheduledMessage] — the server's type has no state
/// field, so this is read from [ImScheduledMessage.messageId] and [ImScheduledMessage.error].
/// 服务端类型没有状态字段，这里由 messageId 与 error 推出来。
enum ImScheduleState {
  /// Neither a message id nor an error: still waiting for its moment (or being sent right now).
  pending,

  /// [ImScheduledMessage.messageId] is set: the message exists.
  sent,

  /// [ImScheduledMessage.error] is the server's fixed `"cancelled by sender"`.
  cancelled,

  /// Any other [ImScheduledMessage.error]: the send was refused when it fired (`"send failed"`, or the
  /// pipeline's own reason).
  failed,
}

/// One schedule, as `msg.schedule` answers and `msg.scheduled` lists. The server's
/// `ScheduledMessage`.
///
/// **There is no state field**; the three settled outcomes read off two members:
///
/// - **pending** — [messageId] and [error] both absent;
/// - **sent** — [messageId] set (and [error] absent);
/// - **cancelled** — [error] is `"cancelled by sender"`;
/// - **failed** — [error] is `"send failed"` or the reason the send pipeline gave.
///
/// [state] does that reading. Settled schedules — sent, cancelled and failed — **stay listed for about
/// 48 hours**, so a cancelled one does not vanish from `msg.scheduled`; filter on [state].
///
/// 没有状态字段：待发 = messageId 与 error 都没有；已发 = messageId 有值；已取消 = error 为
/// "cancelled by sender"；失败 = 其他 error。已了结的条目还会在列表里留约 48 小时。
class ImScheduledMessage {
  const ImScheduledMessage({
    required this.scheduleId,
    required this.appId,
    required this.senderId,
    required this.conversationId,
    required this.sendAt,
    required this.createdAt,
    this.messageId,
    this.error,
  });

  factory ImScheduledMessage.fromJson(Map<String, dynamic> json) {
    final String messageId = imId(json['messageId']);
    return ImScheduledMessage(
      scheduleId: imStringOr(json['scheduleId']),
      appId: imStringOr(json['appId']),
      senderId: imStringOr(json['senderId']),
      conversationId: imStringOr(json['conversationId']),
      sendAt: imIntOr(json['sendAt']),
      createdAt: imIntOr(json['createdAt']),
      messageId: messageId.isEmpty ? null : messageId,
      error: imString(json['error']),
    );
  }

  /// What `msg.cancelScheduled` takes.
  final String scheduleId;

  final String appId;

  /// The caller: a schedule is always the sender's own.
  final String senderId;

  /// The conversation the address resolved to when the schedule was made.
  final String conversationId;

  /// Unix ms, as requested.
  final int sendAt;

  /// Unix ms.
  final int createdAt;

  /// The message's id once it has been sent — digits, read as a string whether it arrives quoted or
  /// bare, like every message id in this package. Absent until then.
  final String? messageId;

  /// Why it did not (or will not) send: `"cancelled by sender"`, `"send failed"`, or the pipeline's
  /// reason. Absent while pending and once sent.
  final String? error;

  /// See the class comment.
  ImScheduleState get state {
    if (messageId != null) return ImScheduleState.sent;
    if (error == null) return ImScheduleState.pending;
    return error == cancelledBySender ? ImScheduleState.cancelled : ImScheduleState.failed;
  }

  /// The server's fixed [error] for a cancelled schedule (`ScheduledMessageStore.ToContract`).
  static const String cancelledBySender = 'cancelled by sender';
}

// ---------------------------------------------------------------------------- folders

/// `conv.upsertFolder`. The server's `UpsertFolderRequest`: create a folder, or **replace** one.
///
/// **A folder holds tags, not conversations.** Filing a conversation is tagging it
/// (`conv.setting` with [ImConversationSetting.tags]); the client then filters `conv.list` by the
/// folder's [tags], [unreadOnly] and [types]. Every tag must already be on one of the caller's
/// conversations, or the save is `1001` naming the unknown ones — tag first, then file.
///
/// **It is a replacement, not a patch**: every member is written as sent, so a rename that sends
/// only the name clears the folder's tags. Use [ImUpsertFolderRequest.edit] to change one member of
/// a folder you hold.
///
/// **Retries.** Without [folderId] the server allocates one, so a create whose reply was lost
/// creates a second folder when repeated. Choose the id yourself (1–64 letters, digits, `-`, `_`,
/// `.`) and the create is safe to repeat: an unknown id is created under that id.
///
/// **Rules** (`IM:Extras` defaults): a blank [name] is `1001`, longer than 64 is cut; more than 16
/// tags is `1001`; `1006` once the caller has 20 folders.
///
/// 文件夹装的是标签不是会话：归档 = 给会话打标签，客户端再按文件夹的条件过滤 conv.list。每个标签必须已经
/// 打在调用者的某个会话上，否则 1001。这是整份替换，不是补丁：只发名字的改名会清掉标签——改一项请用 edit。
/// 不带 folderId 时服务端分配 id，丢了答复重发会建出第二个；自己定 id 则可以放心重发。
class ImUpsertFolderRequest implements ImRequestBody {
  const ImUpsertFolderRequest({
    this.folderId,
    required this.name,
    this.order = 0,
    this.tags = const <String>[],
    this.unreadOnly = false,
    this.types,
  });

  /// [folder] with the members you name changed and every other member kept — the safe way to
  /// rename or re-file, since the save replaces the whole folder.
  /// 以手里的文件夹为底，只改指定的成员——因为保存是整份替换。
  factory ImUpsertFolderRequest.edit(
    ImConversationFolder folder, {
    String? name,
    int? order,
    List<String>? tags,
    bool? unreadOnly,
    List<ImConversationType>? types,
  }) =>
      ImUpsertFolderRequest(
        folderId: folder.folderId,
        name: name ?? folder.name,
        order: order ?? folder.order,
        tags: tags ?? folder.tags,
        unreadOnly: unreadOnly ?? folder.unreadOnly,
        types: types ?? folder.types,
      );

  /// Null to create with a server-allocated id; otherwise the folder to replace, or to create under
  /// this id.
  final String? folderId;

  /// Required and not blank (`1001`); at most 64 characters are kept.
  final String name;

  /// Display order; negative becomes 0. `conv.folders` sorts by this, then by name.
  final int order;

  /// Up to 16, each already on one of the caller's conversations; an empty list is a folder over
  /// every conversation. An empty list is left out of the frame — the server reads a missing `tags`
  /// as empty, so the saved folder is the same, and clearing the tags of an existing folder still
  /// clears them.
  /// 空列表不发：服务端把缺省读作空列表，保存结果相同，清空已有文件夹的标签也照样生效。
  final List<String> tags;

  /// Show only unread conversations.
  final bool unreadOnly;

  /// The conversation types the folder shows; null or empty means all of them (stored as null).
  /// Integers on the wire.
  final List<ImConversationType>? types;

  @override
  Map<String, Object?> toJson() => imBody(<String, Object?>{
        'folderId': folderId,
        'name': name,
        'order': order,
        'tags': tags.isEmpty ? null : tags,
        'unreadOnly': unreadOnly,
        'types': types == null
            ? null
            : <int>[for (final ImConversationType type in types!) type.wireValue],
      });
}

