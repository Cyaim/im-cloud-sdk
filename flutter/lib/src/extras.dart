/// `msg.schedule` / `msg.scheduled` / `msg.cancelScheduled` (scheduled messages),
/// `conv.folders` / `conv.upsertFolder` / `conv.deleteFolder` (conversation folders) and
/// `msg.translate` (message translation) — the T4 calls an ordinary chat application reaches for
/// next. [ImMsgApi] and [ImConvApi] send them; this file holds their request and reply types.
///
/// **No event follows any of them.** A schedule being created, cancelled or sent, and a folder being
/// saved or deleted, push nothing to the caller's other devices: those devices see a change only by
/// listing again (`msg.scheduled`, `conv.folders`). The one thing that does arrive is the message a
/// schedule becomes — an ordinary `evt.message` with a normal seq, on [ImClient.messages] for the
/// receiver and through self-sync for the sender's other devices.
///
/// 这几条调用之后都没有任何推送事件：定时消息的建、取消、发出，文件夹的保存、删除，其他设备都只能重新列一次
/// 才看得见。唯一会到达的是定时消息发出后的那条普通消息（evt.message，正常 seq）。
library;

import 'api.dart' show ImConvApi, ImMsgApi;
import 'client.dart' show ImClient;
import 'json.dart';
import 'models.dart';
import 'protocol.dart';
