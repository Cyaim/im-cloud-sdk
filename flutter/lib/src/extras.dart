/// `msg.translate`. The server's `TranslateRequest`: translate messages the caller can already read,
/// in one conversation, into one language.
///
/// **Gated twice, in this order:** `1204` ([ImErrorCode.planExpired]) when the plan does not include
/// the translation add-on (Enterprise and up, or a trial), then `1203`
/// ([ImErrorCode.featureNotEnabled]) when it does but the deployment or app has no translation
/// provider configured. Both are ordinary refusals — an [ImException] with the code and the server's
/// message — and neither should be latched: a tenant can change both at runtime.
///
/// Then: a [targetLanguage] or [sourceLanguage] that is not a BCP-47 tag, no readable id in
/// [messageIds], or more than 50 ids, is `1001`; `1003` past 60 calls a minute per user.
///
/// 两道闸，按此顺序：套餐不含翻译增值项是 1204，含了但没配翻译服务是 1203——都是普通的、带码与服务端原话的
/// ImException，且都不要在本地记死。之后：语言不是 BCP-47、没有可读的 id、超过 50 条是 1001；每人每分钟 60 次。
class ImTranslateRequest implements ImRequestBody {
  const ImTranslateRequest({
    required this.conversationId,
    required this.messageIds,
    required this.targetLanguage,
    this.sourceLanguage,
  });

  /// Required (`1001` without it). Every message must be in this conversation.
  final String conversationId;

  /// Digits, as [ImMessage.messageId] holds them — strings on the wire, as the server requires. Up to
  /// 50; duplicates are collapsed.
  final List<String> messageIds;

  /// A BCP-47 tag such as `"zh-CN"`; the reply carries it normalised.
  final String targetLanguage;

  /// Null to let the provider detect it.
  final String? sourceLanguage;

  @override
  Map<String, Object?> toJson() => imBody(<String, Object?>{
        'conversationId': conversationId,
        'messageIds': messageIds,
        'targetLanguage': targetLanguage,
        'sourceLanguage': sourceLanguage,
      });
}

/// What `msg.translate` answers. The server's `TranslationResult`.
///
/// **A success can carry failures.** Each message stands or falls on its own in [items]: one the
/// caller may not read, one too long, one past the budget comes back with an
/// [ImTranslatedMessage.error] and no text, while the call itself succeeds. The call fails as a whole
/// only when not a single message could be translated.
/// 成功的答复里也可能有失败：每条消息各自成败，失败的那条带 error、没有 text；只有一条都没译成时整个调用才失败。
class ImTranslationResult {
  const ImTranslationResult({required this.targetLanguage, this.items = const <ImTranslatedMessage>[]});

  factory ImTranslationResult.fromJson(Map<String, dynamic> json) => ImTranslationResult(
        targetLanguage: imStringOr(json['targetLanguage']),
        items: imList(json['items'], ImTranslatedMessage.fromJson),
      );

  /// The requested language, normalised by the server.
  final String targetLanguage;

  final List<ImTranslatedMessage> items;
}

/// One message's translation. The server's `TranslatedMessage`.
class ImTranslatedMessage {
  const ImTranslatedMessage({
    required this.messageId,
    this.text,
    this.cached = false,
    this.error,
  });

  factory ImTranslatedMessage.fromJson(Map<String, dynamic> json) => ImTranslatedMessage(
        messageId: imId(json['messageId']),
        text: imString(json['text']),
        cached: imBool(json['cached']),
        error: imString(json['error']),
      );

  /// Digits, read as a string whether it arrives quoted or bare.
  final String messageId;

  /// The translation; absent when [error] is set.
  final String? text;

  /// Served from the cache rather than the provider (and not billed again).
  final bool cached;

  /// Why this one message was not translated.
  final String? error;
}
